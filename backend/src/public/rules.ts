/** Находки правил в предложении: `ko` проверяет правила scope ko, `ru` — scope ru. */
export function checkSentence(ko: string, ru = ''): { rule: string; severity: Rule['severity']; scope: Rule['scope']; match: string }[] {
  const out: { rule: string; severity: Rule['severity']; scope: Rule['scope']; match: string }[] = []
  for (const r of RULES) {
    if (!r.pattern) continue
    const text = r.scope === 'ko' ? ko : ru
    const m = text ? new RegExp(r.pattern, 'iu').exec(text) : null
    if (m) out.push({ rule: r.id, severity: r.severity, scope: r.scope, match: m[0].trim() })
  }
  return out
}

