import { KNOWN_GRAMMAR } from '../chat/curriculum.js'

/** Разбор голосового разговора: сильная текстовая модель читает расшифровку и пишет отчёт. Голосовая модель только беседует и ошибок по ходу не ищет. */
export const REVIEW_PROMPT = `Ты проверяешь разговор начинающего ученика корейского с голосовым собеседником. Дана расшифровка: «Ученик» это речь ученика, распознанная на слух, «Собеседник» это ответы.

Напиши отчёт по-русски, коротко и просто, строго в таком виде (без таблиц):
**Что получилось** — 1–3 пункта: какие фразы ученик сказал верно.
**Ошибки** — только явные ошибки ученика в слове, частице или форме. Каждая отдельной строкой: «его фраза → как правильно — почему». Нет ошибок: напиши «явных ошибок нет».
**Что повторить** — 1–3 пункта: слова или правила из пройденного.
**Ошибки собеседника** — если собеседник сам ошибся или «исправил» верную фразу ученика, назови это. Если нет, этот раздел пропусти.

Правила:
- Расшифровка речи ученика бывает неточной (похожие звуки, шум, русская речь). Произношение и написание по ней не оценивай. Фразу, которая выглядит как случайный шум или явно не корейская, пропускай. Сомневаешься в ошибке: не пиши её.
- Ничего не выдумывай и не добавляй слов, которых ученик не говорил.
- Пол ученика неизвестен: без родовых форм о нём («получилось», «в твоей фразе»), обращайся на «ты».
- Чтение корейского латиницей или кириллицей не пиши.
- Не предлагай изучать непройденное. Пройдено:
${KNOWN_GRAMMAR}`

/** Расшифровка для модели: реплики по порядку, каждая с подписью; пустой разговор даёт пустую строку. */
export function reviewInput(rows: { role: 'user' | 'assistant'; text: string }[], max = 6000): string {
  const text = rows.map(r => `${r.role === 'user' ? 'Ученик' : 'Собеседник'}: ${r.text}`).join('\n')
  if (!rows.some(r => r.role === 'user')) return ''
  return text.length > max ? text.slice(text.length - max) : text
}
