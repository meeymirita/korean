/** Нужно: ответ (в реплике `only`, если указана) совпадает с `re`; иначе замечание `msg`. */
const need = (re, msg, only) => (r, i) => (only !== undefined && i !== only) || re.test(r) ? '' : msg
/** Нельзя: ответ (в реплике `only`, если указана) совпадает с `re`; тогда замечание `msg`. */
const ban = (re, msg, only) => (r, i) => (only !== undefined && i !== only) || !re.test(r) ? '' : msg

