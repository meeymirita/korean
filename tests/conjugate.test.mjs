import { test, after } from 'node:test'
import assert from 'node:assert/strict'
import { load, close } from './_load.mjs'

const { conjugate, withParticles } = await load('/src/lib/conjugate.ts')
after(close)

/** слово → [вежливая, формальная, прошедшее, будущее, повелительная|null, определение] */
const CASES = {
  가다: ['가요', '갑니다', '갔어요', '갈 거예요', '가세요', '가는'],
  먹다: ['먹어요', '먹습니다', '먹었어요', '먹을 거예요', '먹으세요', '먹는'],
  하다: ['해요', '합니다', '했어요', '할 거예요', '하세요', '하는'],
  공부하다: ['공부해요', '공부합니다', '공부했어요', '공부할 거예요', '공부하세요', '공부하는'],
  오다: ['와요', '옵니다', '왔어요', '올 거예요', '오세요', '오는'],
  보다: ['봐요', '봅니다', '봤어요', '볼 거예요', '보세요', '보는'],
  마시다: ['마셔요', '마십니다', '마셨어요', '마실 거예요', '마시세요', '마시는'],
  주다: ['줘요', '줍니다', '줬어요', '줄 거예요', '주세요', '주는'],
  되다: ['돼요', '됩니다', '됐어요', '될 거예요', '되세요', '되는'],
  쓰다: ['써요', '씁니다', '썼어요', '쓸 거예요', '쓰세요', '쓰는'],
  살다: ['살아요', '삽니다', '살았어요', '살 거예요', '사세요', '사는'],
  듣다: ['들어요', '듣습니다', '들었어요', '들을 거예요', '들으세요', '듣는'],
  모르다: ['몰라요', '모릅니다', '몰랐어요', '모를 거예요', '모르세요', '모르는'],
  부르다: ['불러요', '부릅니다', '불렀어요', '부를 거예요', '부르세요', '부르는'],
  돕다: ['도와요', '돕습니다', '도왔어요', '도울 거예요', '도우세요', '돕는'],
  입다: ['입어요', '입습니다', '입었어요', '입을 거예요', '입으세요', '입는'],
}

test('глаголы: вежливая, формальная, прошедшее, будущее, повелительная, определение', () => {
  for (const [w, exp] of Object.entries(CASES)) {
    const rows = conjugate(w, '동사')
    const by = Object.fromEntries(rows.map(r => [r.label, r.ko]))
    const got = [by['Вежливая форма (наст.)'], by['Формальная форма'], by['Прошедшее время'], by['Будущее время'], by['Повелительная форма'], by['Определение (который…)']]
    assert.deepEqual(got, exp, w)
  }
})

const ADJ = {
  예쁘다: ['예뻐요', '예쁩니다', '예뻤어요', '예쁠 거예요', '예쁜'],
  춥다: ['추워요', '춥습니다', '추웠어요', '추울 거예요', '추운'],
  좋다: ['좋아요', '좋습니다', '좋았어요', '좋을 거예요', '좋은'],
  크다: ['커요', '큽니다', '컸어요', '클 거예요', '큰'],
  그렇다: ['그래요', '그렇습니다', '그랬어요', '그럴 거예요', '그런'],
  멀다: ['멀어요', '멉니다', '멀었어요', '멀 거예요', '먼'],
  바쁘다: ['바빠요', '바쁩니다', '바빴어요', '바쁠 거예요', '바쁜'],
  좁다: ['좁아요', '좁습니다', '좁았어요', '좁을 거예요', '좁은'],
}

test('прилагательные, в том числе ㅂ, ㅎ, ㅡ, ㄹ', () => {
  for (const [w, exp] of Object.entries(ADJ)) {
    const rows = conjugate(w, '형용사')
    const by = Object.fromEntries(rows.map(r => [r.label, r.ko]))
    assert.deepEqual([by['Вежливая форма (наст.)'], by['Формальная форма'], by['Прошедшее время'], by['Будущее время'], by['Определение (какой)']], exp, w)
    assert.equal(by['Повелительная форма'], undefined, 'у прилагательных нет повелительной')
  }
})

test('не глагол и не слово из одного слога без «다» формы не получают', () => {
  assert.equal(conjugate('학생', '명사'), null)
  assert.equal(conjugate('가다 오다', '동사'), null)
})

test('существительное с частицами выбирает форму по последнему звуку', () => {
  const g = Object.fromEntries(withParticles('학생').map(r => [r.label, r.ko]))
  assert.equal(g['Подлежащее (이/가)'], '학생이')
  assert.equal(g['Объект (을/를)'], '학생을')
  assert.equal(g['Это… (이에요/예요)'], '학생이에요')
  const h = Object.fromEntries(withParticles('가게').map(r => [r.label, r.ko]))
  assert.equal(h['Подлежащее (이/가)'], '가게가')
  assert.equal(h['Тема (은/는)'], '가게는')
  assert.equal(h['Вместе (와/과)'], '가게와')
})
