const CONN = ['그리고', '그런데', '그래서']

/** Предложение как текст: без служебных `_`. */
export const longText = (x: LongSentence) => x.ko.replace(/_/g, ' ')

/** Части предложения → группы → слова (без знаков препинания). */
export function longClauses(x: LongSentence): string[][][] {
  return x.ko
    .split(/(?<=[,?.!])\s+/)
    .map(c => c.replace(/[,?.!]/g, '').trim())
    .filter(Boolean)
    .map(c => c.split(' ').map(ch => ch.split('_')))
}

/** Слова верного ответа по порядку учебника. */
export const longWords = (x: LongSentence) => longClauses(x).flat(2)

/** Позиции, на которых может закончиться часть, если начать её с `pos`: связка первая, сказуемое последнее, остальные группы в любом порядке. */
function clauseEnds(chunks: string[][], words: string[], pos: number): number[] {
  const at = (ch: string[], p: number) => ch.every((w, k) => words[p + k] === w)
  let rest = chunks
  if (rest.length > 1 && rest[0]!.length === 1 && CONN.includes(rest[0]![0]!)) {
    if (!at(rest[0]!, pos)) return []
    pos += 1
    rest = rest.slice(1)
  }
  const last = rest[rest.length - 1]!
  const free = rest.slice(0, -1)
  const ends = new Set<number>()
  const walk = (p: number, used: number) => {
    if (used === (1 << free.length) - 1) {
      if (at(last, p)) ends.add(p + last.length)
      return
    }
    free.forEach((ch, i) => {
      if (!(used & (1 << i)) && at(ch, p)) walk(p + ch.length, used | (1 << i))
    })
  }
  walk(pos, 0)
  return [...ends]
}

/** Верно ли собрано: слова те же, части идут по порядку, внутри части группы можно переставлять. */
export function checkLong(x: LongSentence, words: string[]): boolean {
  let starts = [0]
  for (const cl of longClauses(x)) {
    starts = [...new Set(starts.flatMap(p => clauseEnds(cl, words, p)))]
    if (!starts.length) return false
  }
  return starts.includes(words.length)
}

const hasBatchim = (w: string) => {
  const c = w.charCodeAt(w.length - 1)
  return c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 !== 0
}

/** Лишняя плитка к слову: та же основа с неверной частицей (에 ↔ 에서, 을 ↔ 를, 은 ↔ 는, 이 ↔ 가 не по 받침). Пусто, если подменить нечего. */
export function longTrap(w: string): string {
  if (w.endsWith('에서')) return w.slice(0, -1)
  if (w.endsWith('에')) return w + '서'
  const stem = w.slice(0, -1)
  if (stem.length < 1) return ''
  const b = hasBatchim(stem)
  const last = w[w.length - 1]
  if (last === '을' && b) return stem + '를'
  if (last === '를' && !b) return stem + '을'
  if (last === '은' && b) return stem + '는'
  if (last === '는' && !b) return stem + '은'
  if (last === '가' && !b && stem.length > 1) return stem + '이'
  return ''
}
