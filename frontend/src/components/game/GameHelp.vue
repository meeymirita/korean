<script setup lang="ts">
import { ICON, MODE_ICON } from '@/game/icons'
import { MODE_HELP, MODES } from '@/game/modes'

/** Окно «Как играть». Список игр собирается из `MODES` и `MODE_HELP`: новая игра попадает в справку сама. */
defineProps<{ open: boolean }>()
const emit = defineEmits<{ close: [] }>()
</script>

<template>
  <div id="help" class="over help" :class="{ on: open }" @click.self="emit('close')">
    <div class="box" role="dialog" aria-modal="true" aria-labelledby="helpT">
      <div class="top"><h2 id="helpT">Как играть</h2><button class="ghost" id="helpX" @click="emit('close')" type="button" aria-label="Закрыть">✕</button></div>
      <p class="muted">Игра на слова и правила платформы 우리말. Здесь только твои слова и пройденная грамматика.</p>

      <h3>Что где на экране</h3>
      <ul>
        <li><b>Сверху</b>: кнопка «← К списку игр» и название игры. Другую игру выбирай в списке игр.</li>
        <li><b>В центре</b>: задание. Рядом с его названием кнопка «?»: что делать именно в этой игре и пример.</li>
        <li><b>Под заданием</b>: кнопки «Обновить вопрос», «Блиц», «На выживание», «Как играть» и «Настройки».</li>
        <li><b>Справа</b>: счёт, серия, уровень, цель дня и списки «История», «Слабые слова», «Слова», «Рекорды».</li>
      </ul>

      <h3>Как отвечать</h3>
      <ul>
        <li>Нажми на вариант мышкой или клавишей с его номером (<kbd>1</kbd>–<kbd>9</kbd>).</li>
        <li>Зелёный значит верно, красный неверно. Под вопросом появится разбор.</li>
        <li>Дальше: кнопка «Дальше →» или <kbd>Enter</kbd>. Разбор не закрывается сам (сам идёт дальше только «Блиц»).</li>
        <li>Слово, на котором ошибся, вернётся через 3–4 вопроса.</li>
      </ul>

      <h3>Уровни: одно предложение или текст</h3>
      <ul>
        <li>У большинства игр над заданием три уровня: «Простой» (один вопрос), «Рассказ 2–4» и «Длинный 5–10» (несколько предложений с пропусками).</li>
        <li>В тексте: нажми плитку внизу, потом пропуск. Нажми на заполненный пропуск, чтобы убрать ответ. Там, где форму нужно написать, впиши её в поле.</li>
        <li>Значок слева от предложения показывает его перевод, повторное нажатие прячет.</li>
        <li>Проверка в конце, по кнопке «Проверить»: пустые пропуски она обведёт рамкой. После неё «Разбор» объясняет каждое предложение, «Разбор всего» сразу все, а за текст без ошибок даётся бонус к опыту.</li>
      </ul>

      <h3>Игры</h3>
      <ul id="helpModes">
        <li v-for="m in MODES" :key="m.id">
          <span class="hm-ico"><img class="gi-img" :src="ICON[MODE_ICON[m.id]!] ?? ''" alt="" aria-hidden="true" /></span>
          <b>{{ m.name }}</b>: {{ MODE_HELP[m.id] ? MODE_HELP[m.id]![0].split(' Над заданием три уровня')[0] : 'вопросы из разных игр вперемешку.' }}
          <div v-if="MODE_HELP[m.id]" class="hm-ex">{{ MODE_HELP[m.id]![1] }}</div>
        </li>
      </ul>

      <h3>Собери предложение</h3>
      <p>Нажимай корейские плитки по порядку (или клавишами <kbd>1</kbd>–<kbd>9</kbd>). Среди плиток есть лишние: с неверной частицей, временем или местом. <kbd>Enter</kbd> проверяет, <kbd>Backspace</kbd> убирает последнее слово, <kbd>H</kbd> ставит следующее слово (подсказка), <kbd>T</kbd> подписывает плитки переводом.</p>

      <h3>Подсказка 50/50</h3>
      <p>В вопросах с вариантами есть кнопка «50/50» (или клавиша <kbd>H</kbd>): она убирает два неверных ответа. Три подсказки на игру, в блице подсказок нет.</p>

      <h3>Правая панель</h3>
      <ul>
        <li><b>Верно / неверно / точность</b>: счёт с момента, как открыта страница.</li>
        <li><b>Серия</b>: сколько верных ответов подряд. Одна ошибка обнуляет её.</li>
        <li><b>Испечено</b>: каждые 10 верных ответов (за всё время) пекут один хлебушек.</li>
        <li><b>Уровень</b> растёт от опыта: +10 за верный ответ (+15 и +20 за задания сложнее), ещё +5 за каждые пять верных подряд. Звания идут от «Искры» до «Вечности».</li>
        <li><b>Цель дня</b>: число верных ответов за сегодня, меняется в настройках кабинета. Завтра счётчик начнётся заново.</li>
        <li><b>История</b>: твои ответы. У ошибок видно, что было выбрано.</li>
        <li><b>Слабые слова</b>: слова с ошибками. Они выпадают чаще, пока не ответишь верно.</li>
        <li><b>Слова</b>: все слова игры с поиском. <b>Рекорды</b>: лучшие серии, блиц и выживание.</li>
      </ul>

      <h3>Блиц и выживание</h3>
      <ul>
        <li><b>Блиц</b>: 30, 60 или 120 секунд (выбирается в настройках). Ответь на как можно больше вопросов, ответы идут быстро и сами. Лучший результат запоминается.</li>
        <li><b>На выживание</b>: 3 или 5 жизней либо без ограничения. Каждая ошибка забирает жизнь.</li>
      </ul>

      <h3>Настройки</h3>
      <ul>
        <li><b>Какие слова брать</b>: группы слов для вопросов.</li>
        <li><b>Формы глаголов</b>: настоящее, прошедшее или оба; будущее (거예요) включается отдельно.</li>
        <li><b>Блиц и выживание</b>: сколько секунд и сколько жизней.</li>
        <li><b>Чтение кириллицей</b>: показывается под корейским словом. Можно выключить, чтобы читать без подсказки.</li>
        <li><b>Сбросить статистику игры</b>: обнуляет счёт, рекорды, слабые слова и историю ответов в этой игре. Уровень, цель дня и остальной прогресс сайта не трогает.</li>
      </ul>

      <p class="muted" style="margin-top:14px">Счёт игры, рекорды и история ответов хранятся в браузере на этом устройстве. Очки слов, опыт и цель дня идут в общий прогресс сайта.</p>
      <div style="display:flex;justify-content:flex-end;margin-top:12px"><button class="primary" id="helpOk" @click="emit('close')" type="button">Понятно, играем</button></div>

    </div>
  </div>
</template>
