/**
 * Яндекс.Метрика (счётчик 114693891, решение владельца 2026-11-26): вебвизор записывает содержимое страниц,
 * поэтому он работает только на открытых страницах. Всё, что под токеном (`/korean/...`, `/game`, `/upload`), он не видит:
 * 1) счётчик вообще не подключается, если сайт открыли сразу на закрытой странице (скрипт в `nuxt.config.ts`);
 * 2) если зашли на открытую и перешли внутри сайта на закрытую, на `body` ставятся классы Метрики
 *    `ym-hide-content` и `ym-disable-keys` (плагин `plugins/metrika-mask.client.ts`): текст скрыт, нажатия клавиш не пишутся.
 * `/korean/home` тоже считается закрытой: в оболочке `/korean` у вошедшего владельца видны личные счётчики.
 */
export const OPEN_SRC = '^/(?:(?:about|history|growth|me|dict|ru)(?:/|$)|$)'
export const isOpenPath = (path: string) => new RegExp(OPEN_SRC).test(path)
