/** Вопрос на экране: варианты перемешаны, `correct` это номер верного. */
export interface ShownQ {
  q: string
  options: string[]
  correct: number
  line: number
}

/** Вопросы попытки: `n` случайных из банка, у каждого варианты в случайном порядке. */
export function pickQuiz(bank: readonly QuizQ[], n = QUIZ_SHOWN): ShownQ[] {
  return shuffle(bank)
    .slice(0, n)
    .map(b => {
      const options = shuffle(b.options)
      return { q: b.q, options, correct: options.indexOf(b.options[0]), line: b.line }
    })
}

/** Пары слов: русское значение (только первое, до «;» или «,») и корейское слово; `min`…`max` случайных; меньше `min` пар в блок не годится (пусто). */
export function pickPairs<T extends { k: string; t: string }>(words: readonly T[], max = PAIRS_MAX, min = PAIRS_MIN): { k: string; t: string }[] {
  const uniq = new Map<string, string>()
  for (const w of words) {
    const t = w.t.split(/[;,]/)[0]!.trim()
    if (t && !uniq.has(w.k)) uniq.set(w.k, t)
  }
  // два слова с одним русским значением дали бы неоднозначную пару: оставляем первое
  const seen = new Set<string>()
  const list = [...uniq].flatMap(([k, t]) => (seen.has(t) ? [] : (seen.add(t), [{ k, t }])))
  return list.length < min ? [] : shuffle(list).slice(0, max)
}

/** Часть фразы рассказа: текст или пропуск (номер пропуска = номер слова в `gaps`). */
export type StoryPart = { t: string } | { gap: number }

/** Фразы эпизода с пропусками: слово из `gaps` заменяется пропуском (первое совпадение целого слова, знаки в конце остаются). */
export function storyLines(lines: readonly VlogLine[], story: VlogTestData['story']): StoryPart[][] {
  const used = new Set<number>()
  return lines.slice(story.from, story.to + 1).map(l =>
    l.ko.split(' ').flatMap((tok, i): StoryPart[] => {
      const core = tok.replace(/[.,?!]+$/, '')
      const gap = story.gaps.indexOf(core)
      const lead: StoryPart[] = i ? [{ t: ' ' }] : []
      if (gap < 0 || used.has(gap)) return [...lead, { t: tok }]
      used.add(gap)
      return [...lead, { gap }, { t: tok.slice(core.length) }]
    }),
  )
}

/** Блок «Порядок»: сколько событий стоит на своём месте (`order[i]` — номер события в правильном порядке, стоящего на i-м месте). */
export const orderScore = (order: readonly number[]) => order.filter((e, i) => e === i).length

/** Перемешанный порядок событий, не совпадающий с правильным. */
export function shuffledOrder(n: number): number[] {
  const base = Array.from({ length: n }, (_, i) => i)
  if (n < 2) return base
  let o = shuffle(base)
  while (o.every((e, i) => e === i)) o = shuffle(base)
  return o
}

