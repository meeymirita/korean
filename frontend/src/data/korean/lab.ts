/** Есть ли у слова 받침 (согласная внизу последнего слога). */
export const hasBatchim = (w: string) => {
  const c = w.charCodeAt(w.length - 1) - 0xac00
  return c >= 0 && c < 11172 && c % 28 !== 0
}

