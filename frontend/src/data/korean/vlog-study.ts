/**
 * Рассказ в влогах ChoiSusu звучит несколько раз подряд с тем же текстом (слушаем, с субтитрами, с двумя языками, повторяем за автором с паузами).
 * В первом проходе автор иногда склеивает начало в одну строку, а в повторах режет на две, поэтому повтор ищем так: следующая строка, с которой
 * начинается первая фраза (достаточно длинная, от 8 знаков). Проход заканчивается перед первым повтором; `count` = сколько проходов.
 */
export function passes(lines: readonly VlogLine[]): { first: VlogLine[]; count: number } {
  const head = lines[0]?.ko
  if (!head) return { first: [], count: 0 }
  const starts = lines.flatMap((l, i) => (i > 0 && l.ko.length >= 8 && head.startsWith(l.ko) ? [i] : []))
  return { first: starts.length ? lines.slice(0, starts[0]) : [...lines], count: starts.length + 1 }
}

